"""Настройки пайплайна. Меняются либо здесь, либо флагами run.py."""

from dataclasses import dataclass, field


# Сколько позиций из выдачи усредняем (по условию задачи — первые 5).
TOP_N = 5

# Минимум релевантных позиций, при котором средняя цена считается достоверной.
# Если найдено меньше — значение всё равно пишется, но помечается в колонке
# "найдено позиций", чтобы такие строки можно было отфильтровать глазами.
MIN_MATCHES = 1

# Сколько позиций выдачи просматривать в поисках релевантных, прежде чем сдаться.
# Выдача маркетплейсов замусорена аксессуарами и подделками, поэтому берём
# запас: первые TOP_N *релевантных*, а не первые TOP_N подряд.
SCAN_DEPTH = 30

# Отсев ценовых выбросов внутри уже отобранной пятёрки: позиция отбрасывается,
# если её цена отличается от медианы группы более чем в OUTLIER_RATIO раз.
# Спасает от "чехол для X" за 300 р. рядом с самим X за 30 000 р.
OUTLIER_RATIO = 4.0

# Пауза между запросами к одной площадке, секунды. Ozon и Яндекс.Маркет
# начинают отдавать капчу при более агрессивном темпе.
DELAY_WB = 0.4
DELAY_OZON = 2.5
DELAY_YM = 3.0

# Сколько раз повторять запрос при сетевой ошибке / капче.
MAX_RETRIES = 3
RETRY_BACKOFF = 4.0

# Регион для цен. WB: dest определяет склад и, соответственно, цену.
# -1257786 — Москва. Другие частые значения: -1123300 (СПб), 123589350 (Казань).
WB_DEST = -1257786

# Playwright: запускать браузер без окна. Для отладки капчи ставьте False.
HEADLESS = True

# Таймаут загрузки страницы в браузере, мс.
PAGE_TIMEOUT = 45000


@dataclass
class Settings:
    top_n: int = TOP_N
    scan_depth: int = SCAN_DEPTH
    outlier_ratio: float = OUTLIER_RATIO
    wb_dest: int = WB_DEST
    headless: bool = HEADLESS
    page_timeout: int = PAGE_TIMEOUT
    max_retries: int = MAX_RETRIES
    retry_backoff: float = RETRY_BACKOFF
    sources: tuple = field(default=("ozon", "yandex", "wb"))
